import http from 'k6/http';
import {check, sleep} from 'k6';
import exec from 'k6/execution';
import {createStandardMetrics} from "../../utils/metrics-utils.js";
import {
  ActorCredentials,
  buildHeaders,
  determineStage,
  endpoints,
  generatePositiveLong,
  getOptions, randomFiscalCode,
  setupAuth
} from "../../utils/utils.js";
import {buildGpdMessagePayload} from "../../utils/sender-payloads.js";
import {uuidv4} from 'https://jslib.k6.io/k6-utils/1.4.0/index.js';

/** Run start timestamp (ms). */
const START_TIME = Date.now();

/** Number of virtual users. */
const VU_COUNT_SET = Number(__ENV.VU_COUNT_SET) || 10;

/** Total shared iterations. */
const ITERATIONS = Number(__ENV.ITERATIONS) || 1000;

/** Optional sleep between iterations (seconds). */
const SLEEP_ITER = Number(__ENV.SLEEP_ITER) || 0;

/** Optional PSP tax code. If not provided, the value defaults to null. */
const PSP_TAX_CODE = __ENV.PSP_TAX_CODE || null;

/** Gpd message Operation. If not provided, the value defaults to CREATE. */
const OPERATION = __ENV.OPERATION || "CREATE";

/** Gpd message Status. If not provided, the value defaults to VALID. */
const STATUS = __ENV.STATUS || "VALID";

/**
 * Whether the test generates new operation IDs (CREATE/UPDATE with status VALID)
 * or operates on the existing ones loaded from `gpd-message-id.json` (e.g. DELETE).
 */
const GENERATE_NEW_IDS = ["CREATE", "UPDATE"].includes(OPERATION) && STATUS === "VALID";

/** Debtor Service Provider ID used for the activation (env: DEBTOR_SERVICE_PROVIDER_ID). @type {string} */
const DEBTOR_SERVICE_PROVIDER_ID = String(__ENV.DEBTOR_SERVICE_PROVIDER_ID);

/** Load profile to use. See file-level doc comment above for the accepted values. */
const SCENARIO = __ENV.SCENARIO || 'custom';

/** Scenario names backed by the predefined ramps/durations in `progressiveOptions` (utils.js). */
const PREDEFINED_SCENARIOS = [
  'stress_test', 'soak_test', 'spike_test',
  'stress_test_fixed_user', 'soak_test_fixed_user', 'spike_test_fixed_user'
];

if (SCENARIO !== 'custom' && !PREDEFINED_SCENARIOS.includes(SCENARIO)) {
  const expectedScenarios = PREDEFINED_SCENARIOS.map((s) => "'" + s + "'").join(', ');
  throw new Error(
      `❌ Unknown SCENARIO "${SCENARIO}". Expected one of: 'custom', ${expectedScenarios}`
  );
}

/** Input file with existing operation IDs (generated by `script/create-gpd-message.js`). */
const OPERATION_IDS_FILE = '../../json-file/rtp-sender/gpd-message-id.json';

/**
 * Loads unique operation IDs from `OPERATION_IDS_FILE`.
 * Fails fast with a clear message if the file is missing or contains no IDs.
 *
 * @returns {string[]} Unique operation IDs.
 */
function loadOperationIds() {
  const hint = `OPERATION=${OPERATION} STATUS=${STATUS} requires existing operation IDs in ` +
      `json-file/rtp-sender/gpd-message-id.json: run script/create-gpd-message.js first`;

  let content;
  try {
    content = open(OPERATION_IDS_FILE);
  } catch (e) {
    throw new Error(`❌ File not found. ${hint}`);
  }

  const ids = Array.from(new Set(JSON.parse(content))).map(String);
  if (ids.length === 0) {
    throw new Error(`❌ File contains no operation IDs. ${hint}`);
  }
  return ids;
}

/** Existing operation IDs, loaded only when new IDs are not generated. @type {string[]} */
const operationIds = GENERATE_NEW_IDS ? [] : loadOperationIds();

/**
 * Standard custom metrics used by this test.
 * @typedef {Object} StandardMetrics
 * @property {import('k6/metrics').Rate} currentRPS
 * @property {import('k6/metrics').Counter} failureCounter
 * @property {import('k6/metrics').Counter} successCounter
 * @property {import('k6/metrics').Trend} responseTimeTrend
 */
const {
  currentRPS,
  failureCounter,
  successCounter,
  responseTimeTrend
} = createStandardMetrics();

/**
 * k6 execution configuration.
 * Uses shared-iterations executor with configurable VUs and iterations.
 */
export const options = PREDEFINED_SCENARIOS.includes(SCENARIO)
    ? {
      ...getOptions(SCENARIO, 'sendMessage'),
      setupTimeout: '5m'
    }
    : {
      ...getOptions('stress_test_fixed_user', 'sendMessage'),
      setupTimeout: '5m',
      scenarios: {
        stress_test_fixed_user: {
          executor: 'shared-iterations',
          vus: VU_COUNT_SET,
          iterations: GENERATE_NEW_IDS ? ITERATIONS : operationIds.length,
          maxDuration: '30m',
          gracefulStop: '30m',
          exec: 'sendMessage'
        }
      }
    };

/**
 * k6 setup function.
 *
 * Executed once before the test starts.
 * Prepares and wraps fiscal codes to be shared across VUs.
 *
 * @returns {{ fiscalCode: string, auth: string }}
 */
export function setup() {
  const activationAuth = setupAuth(ActorCredentials.DEBTOR_SERVICE_PROVIDER);
  const activationHeaders = buildHeaders(activationAuth.access_token);

  const fiscalCode = randomFiscalCode();

  const payload = {
    payer: {
      fiscalCode: fiscalCode,
      rtpSpId: DEBTOR_SERVICE_PROVIDER_ID
    }
  };

  const url = endpoints.activations;
  const activationRes = http.post(url, JSON.stringify(payload), { headers: activationHeaders });
  check(activationRes, { 'activation 201': r => r.status === 201 });

  if (activationRes.status !== 201) {
    throw new Error(`❌ Failed to create activation for ${fiscalCode}. Status: ${activationRes.status}`);
  }

  const auth = setupAuth(ActorCredentials.RTP_CONSUMER).access_token;

  return {fiscalCode: fiscalCode, auth: auth};
}

/**
 * Main stress test scenario function.
 *
 * For each iteration:
 *  - Calculates time-based tags for metrics
 *  - Picks the operation ID: a new one when `GENERATE_NEW_IDS`, otherwise the
 *    next one from `gpd-message-id.json` (aborts the test when exhausted)
 *  - Sends a GPD message request
 *  - Tracks success/failure and response time
 *
 * @param {{ fiscalCode: string , auth: string}} data - Shared setup data
 */
export function sendMessage(data) {
  const elapsedSeconds = (Date.now() - START_TIME) / 1000;

  const tags = {
    timeWindow: Math.floor(elapsedSeconds / 10) * 10,
    stage: determineStage(elapsedSeconds),
    vu: String(__VU),
  };

  currentRPS.add(1, tags);

  const headers = {
    ...buildHeaders(data.auth),
    "Idempotency-Key": uuidv4()
  };

  let operationId;
  if (GENERATE_NEW_IDS) {
    operationId = generatePositiveLong();
  } else {
    const idx = exec.scenario.iterationInTest;
    if (idx >= operationIds.length) {
      exec.test.abort('Operation IDs exhausted');
      return;
    }
    operationId = operationIds[idx];
  }

  const payload = buildGpdMessagePayload(
      data.fiscalCode,
      operationId,
      OPERATION,
      STATUS,
      "77777777777",
      PSP_TAX_CODE
  );

  const start = Date.now();
  let res = http.post(endpoints.gpdMessage, JSON.stringify(payload), {headers});
  const duration = Date.now() - start;

  responseTimeTrend.add(duration, tags);

  if (res.status === 200) {
    successCounter.add(1, tags);
  } else {
    failureCounter.add(1, tags);
    console.error(`❌ VU #${__VU}: Failed send gpd message — Status ${res.status}`);
  }

  check(res, {
    'GpdMessage: status is 200': (r) => r.status === 200
  });

  if (SLEEP_ITER > 0) {
    sleep(SLEEP_ITER);
  }
}
